.INCLUDE <m328Pdef.inc>
.DSEG
.ORG SRAM_START

    Count: .BYTE 1

.CSEG
.ORG 0x0000
    RJMP START

START:
    LDI R16, HIGH(RAMEND)
    OUT SPH, R16
    LDI R16, LOW(RAMEND)
    OUT SPL, R16

    CBI GPIOR0, 7
    CBI GPIOR0, 2

LOOP:
    SBIC GPIOR0, 3
    RJMP BOTAO_PRESS

BOTAO_NAO_PRESS:
    CBI GPIOR0, 7
    CBI GPIOR0, 2

    RJMP LOOP

BOTAO_PRESS:
    SBI GPIOR0, 7
    SBI GPIOR0, 2

    RCALL ATRASO

    CBI GPIOR0, 7
    CBI GPIOR0, 2

    RCALL ATRASO

    RJMP LOOP

ATRASO:
    PUSH R16
    PUSH R17
    PUSH R18
    IN R16, SREG
    PUSH R16

    LDI R16, 20
    STS Count, R16

LOOP_ATRASO_EXT:
    LDI R17, 200
LOOP_ATRASO_MID:
    LDI R18, 250
LOOP_ATRASO_INT:
    DEC R18
    BRNE LOOP_ATRASO_INT

    DEC R17
    BRNE LOOP_ATRASO_MID

    LDS R16, Count
    DEC R16
    STS Count, R16
    BRNE LOOP_ATRASO_EXT

    POP R16
    OUT SREG, R16
    POP R18
    POP R17
    POP R16

    RET